// Feed current-catalog.sql from the effective isolated schema, never a daily credential.
// node scripts/schema/generate-types.mjs <catalog.json> <output.ts> [--check]
import {readFileSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
export function generateDatabaseTypes(catalog){
 const schemas=['public','local_identity','loop_internal'],q=JSON.stringify;
 const types=new Map(catalog.types.map(t=>[t.schema+'.'+t.name,t]));
 const relations=new Map(catalog.relations.map(r=>[r.schema+'.'+r.name,r]));
 function type(key){
  const t=types.get(key);if(!t)throw Error('Unsupported catalog type: '+key);
  if(t.base)return type(t.base);
  if(t.enum)return t.enum.map(q).join(' | ');
  if(t.category==='A')return `(${type(t.element)})[]`;
  const r=relations.get(key);if(r)return `Database[${q(r.schema)}][${q(['v','m'].includes(r.kind)?'Views':'Tables')}][${q(r.name)}]['Row']`;
  const name=t.name;
  if(['json','jsonb'].includes(name))return 'Json';
  if(name==='void')return 'undefined';
  if(name==='bool')return 'boolean';
  if(['int2','int4','int8','float4','float8','numeric','oid'].includes(name))return 'number';
  if(['text','varchar','bpchar','name','uuid','date','timestamp','timestamptz','time','timetz','interval','bytea','inet','cidr','macaddr','char','pg_lsn'].includes(name))return 'string';
  // SQL record without declared OUT columns cannot be decoded from the signature.
  if(name==='record')return 'Record<string, unknown>';
  throw Error('Unsupported catalog type: '+key);
 }
 const field=(c,mode)=>`${q(c.name)}${mode==='Update'||mode==='Insert'&&(c.nullable||c.default)?'?':''}: ${c.generated&&mode!=='Row'?'never':type(c.type)+(c.nullable?' | null':'')};`;
 let output=`// GENERATED by scripts/schema/generate-types.mjs from current-catalog.sql. Do not edit.\n// Effective contract SHA256: ${createHash('sha256').update(JSON.stringify(catalog)).digest('hex')}\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = {\n`;
 for(const schema of schemas){
  output+=` ${q(schema)}: {\n`;
  for(const group of ['Tables','Views']){
   output+=`  ${group}: {\n`;
   for(const r of catalog.relations.filter(r=>r.schema===schema&&(['v','m'].includes(r.kind)?'Views':'Tables')===group)){
    output+=`   ${q(r.name)}: {\n`;
    for(const mode of ['Row','Insert','Update'])output+=`    ${mode}: { ${r.columns.map(c=>field(c,mode)).join(' ')} };\n`;
    output+=`    Relationships: ${q(r.relationships)};\n   };\n`;
   }
   output+='  };\n';
  }
  output+='  Functions: {\n';
  const functions=catalog.functions.filter(f=>f.schema===schema),names=[...new Set(functions.map(f=>f.name))];
  for(const name of names){
   const overloads=functions.filter(f=>f.name===name).map(f=>{
    const args=f.args.filter(a=>['i','b','v'].includes(a.mode)),out=f.args.filter(a=>['o','b','t'].includes(a.mode));
    const returns=out.length?`{ ${out.map(a=>`${q(a.name)}: ${type(a.type)} | null;`).join(' ')} }`:type(f.returnType);
    return `{ Args: ${args.length?'{ '+args.map(a=>`${q(a.name)}${a.optional?'?':''}: ${type(a.type)} | null;`).join(' ')+' }':'Record<string, never>'}; Returns: ${returns}${f.set?'[]':''} }`;
   });
   output+=`   ${q(name)}: ${overloads.join(' | ')};\n`;
  }
  output+='  };\n  Enums: {\n';
  for(const t of catalog.types.filter(t=>t.schema===schema&&t.enum))output+=`   ${q(t.name)}: ${type(schema+'.'+t.name)};\n`;
  output+='  };\n };\n';
 }
 return output+'};\n';
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const [input,output,check]=process.argv.slice(2);if(!input||!output||check&&check!=='--check')throw Error('Usage: generate-types.mjs <catalog.json> <output.ts> [--check]');
 const text=generateDatabaseTypes(JSON.parse(readFileSync(input,'utf8')));
 if(check){if(readFileSync(output,'utf8')!==text)throw Error('Generated SQL types are stale');}else writeFileSync(output,text);
}
