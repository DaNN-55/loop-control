import { execFileSync } from 'node:child_process';
import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import postcss from 'postcss';

// Compile only adopted component classes, then contain the entire reset/theme in
// a native CSS scope shared by the current local application and its portals.
const temp = await mkdtemp(join(tmpdir(), 'dan-ui-css-'));
try {
  const compiled = join(temp, 'compiled.css');
  execFileSync(process.execPath, [
    'node_modules/@tailwindcss/cli/dist/index.mjs',
    '-i', 'src/ui/dan-ui/styles/entry.css', '-o', compiled,
  ], { stdio: 'inherit' });
  const css = postcss.parse(await readFile(compiled, 'utf8'));
  css.walkAtRules('layer', rule => rule.nodes ? rule.replaceWith(...rule.nodes) : rule.remove());
  const properties = [];
  css.walkAtRules('property', rule => { properties.push(rule.clone()); rule.remove(); });
  css.walkRules(rule => {
    rule.selector = rule.selector.replace(/:root\s*,\s*:host/g, ':scope')
      .replace(/\.dark-mode/g, ':scope:where([data-theme="dark"], [data-theme="dark"] *)');
  });
  const scope = postcss.atRule({ name: 'scope', params: '(.dan-ui)' });
  scope.append(css.nodes);
  const result = postcss.root();
  result.append(postcss.comment({ text: 'Generated by npm run ui:build. Untitled UI MIT; see UPSTREAM.json. All rendered rules are scoped to .dan-ui.' }));
  result.append(...properties, scope);
  await writeFile('src/ui/dan-ui/styles/scoped.css', result.toString() + '\n');
} finally {
  await rm(temp, { recursive: true, force: true });
}
