// @vitest-environment node
import {it,expect} from 'vitest';
import {readFile,copyFile} from 'node:fs/promises';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {embeddedStudioFixture} from './embeddedStudio.fixture';
import {editStudioDocument} from './studioDocument.fixture';
it.skipIf(process.env.LOOP_EMBEDDED_STUDIO_ACCEPTANCE!=='1')('Owner opens the real Studio and saves its versioned workspace through native HTTP',async()=>{
  const f=await embeddedStudioFixture();
  try{
    const media=(await f.c.query("SELECT id,sha256 FROM public.artifacts WHERE episode_id=$1 AND artifact_type='render'",[f.episode])).rows[0];
    const response=await fetch(f.origin+'/api/local/artifacts/'+media.id,{headers:{Cookie:'loop_owner_session='+f.token}});
    expect(response.status).toBe(200);expect(response.headers.get('content-type')).toBe('video/mp4');
    expect(createHash('sha256').update(Buffer.from(await response.arrayBuffer())).digest('hex')).toBe(media.sha256);
    const opened=await f.request('openStudio',{projectRelativePath:f.boardPath});
    expect(opened.status,JSON.stringify(opened.body)).toBe(200);
    expect(new URL(opened.body.studioUrl).searchParams.get('lcBridge')).toBe('1');
    const workspace=opened.body.workspace;
    const saved=await f.request('saveStudio',{sourceProjectRelativePath:f.boardPath,workspaceRelativePath:workspace.relativePath,projectId:workspace.projectId,expectedWorkspaceSha256:workspace.sha256});
    expect(saved.status,JSON.stringify(saved.body)).toBe(200);
    expect(saved.body.projectId).toBe(workspace.projectId);
    expect(saved.body.sha256).toMatch(/^[a-f0-9]{64}$/);
    const data={sourceProjectRelativePath:f.boardPath,workspaceRelativePath:workspace.relativePath,projectId:workspace.projectId,expectedWorkspaceSha256:saved.body.sha256};
    expect((await f.request('saveStudio',data,{csrf:false})).status).toBe(403);
    expect((await f.request('saveStudio',data,{origin:'http://foreign.invalid'})).status).toBe(403);
    expect((await f.request('saveStudio',data,{token:f.otherToken})).status).toBe(404);
    expect((await f.request('saveStudio',data,{token:'0'.repeat(64)})).status).toBe(401);
    expect((await f.request('saveStudio',{...data,projectId:'another-project'})).status).toBe(409);
    expect((await f.request('saveStudio',{...data,workspaceRelativePath:'../outside.json'})).status).toBe(409);
    expect((await f.request('saveStudio',{...data,expectedWorkspaceSha256:'invalid'})).status).toBe(400);
    const stale=await f.request('saveStudio',{sourceProjectRelativePath:f.boardPath,workspaceRelativePath:workspace.relativePath,projectId:workspace.projectId,expectedWorkspaceSha256:'0'.repeat(64)});
    expect(stale.status,JSON.stringify(stale.body)).toBe(409);
    let original:any;
    await editStudioDocument(opened.body.studioUrl,workspace.projectId,doc=>{
      original=structuredClone(doc);
      const unapproved={...structuredClone(doc.assets.find((asset:any)=>asset.kind==='video')),id:'unapproved',name:'unapproved.mp4',src:'/media/uploads/unapproved.mp4'};
      doc.assets.push(unapproved);
      const item=doc.timelines[0].items.find((item:any)=>item.kind==='video');
      item.sourceAssetId=unapproved.id;item.src=unapproved.src;
    });
    const injected=await fetch(new URL(`/api/project-store/entry?key=${encodeURIComponent('project:'+workspace.projectId)}`,opened.body.studioUrl),{headers:{'Sec-Fetch-Site':'none'}});
    expect(injected.status).toBe(200);
    expect((await injected.json()).value.timelines[0].items.find((item:any)=>item.kind==='video')).toMatchObject({sourceAssetId:'unapproved',src:'/media/uploads/unapproved.mp4'});
    const before=await readFile(join(f.assetRoot,workspace.relativePath),'utf8');
    const denied=await f.request('saveStudio',data);
    expect(denied.status,JSON.stringify(denied.body)).toBe(409);
    expect(await readFile(join(f.assetRoot,workspace.relativePath),'utf8')).toBe(before);
    expect((await f.request('openStudio',{projectRelativePath:f.boardPath})).status).toBe(409);
    expect(await readFile(join(f.assetRoot,workspace.relativePath),'utf8')).toBe(before);
    await editStudioDocument(opened.body.studioUrl,workspace.projectId,()=>original);
    const restored=await f.request('saveStudio',data);expect(restored.status,JSON.stringify(restored.body)).toBe(200);
    data.expectedWorkspaceSha256=restored.body.sha256;
    await editStudioDocument(opened.body.studioUrl,workspace.projectId,doc=>{
      doc.timelines[0].items.find((i:{kind:string})=>i.kind==='video').transform.x=17;
    });
    const changed=await f.request('saveStudio',data);expect(changed.status,JSON.stringify(changed.body)).toBe(200);expect(changed.body.sha256).not.toBe(data.expectedWorkspaceSha256);
    expect((await f.request('saveStudio',data)).status).toBe(409);
    saved.body.sha256=changed.body.sha256;data.expectedWorkspaceSha256=changed.body.sha256;
    await f.closeStudio();
    expect((await f.request('saveStudio',data)).status).toBe(409);
    const reopened=await f.request('openStudio',{projectRelativePath:f.boardPath});
    expect(reopened.status,JSON.stringify(reopened.body)).toBe(200);
    expect(reopened.body.workspace.sha256).toBe(saved.body.sha256);
    const row=(await f.c.query('SELECT id,input_snapshot FROM public.tasks WHERE episode_id=$1',[f.episode])).rows[0];
    const nextPath=`episodes/${f.episode}/replacement.mp4`,snapshot=row.input_snapshot;
    await copyFile(join(f.assetRoot,snapshot.review_render.members[0].relative_path),join(f.assetRoot,nextPath));
    snapshot.review_render.members[0].relative_path=nextPath;
    await f.c.query('UPDATE public.tasks SET input_snapshot=$2 WHERE id=$1',[row.id,snapshot]);
    const validBefore=await readFile(join(f.assetRoot,workspace.relativePath),'utf8');
    const warning=await f.request('openStudio',{projectRelativePath:f.boardPath});
    expect(warning.status,JSON.stringify(warning.body)).toBe(200);expect(warning.body.replacementWarning).toBeTruthy();expect(warning.body.studioUrl).toBeUndefined();
    expect(await readFile(join(f.assetRoot,workspace.relativePath),'utf8')).toBe(validBefore);
    const replacement=await f.request('openStudio',{projectRelativePath:f.boardPath,replaceWorkspace:true});
    expect(replacement.status,JSON.stringify(replacement.body)).toBe(200);expect(replacement.body.studioUrl).toBeTruthy();
  }finally{await f.close();}
},180_000);
