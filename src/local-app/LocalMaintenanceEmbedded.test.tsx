import {cleanup, render, screen, waitFor, within} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import {afterEach, expect, it, vi} from 'vitest';
import {useState} from 'react';
import {LocalMaintenancePanel} from './LocalMaintenancePanel';
import {LocalSystemStatus} from './LocalSystemStatus';
import {localRequest} from './client';
vi.mock('./client',()=>({localRequest:vi.fn()}));
vi.mock('./LocalConnectionsPanel',()=>({LocalConnectionsPanel:()=> <label>连接草稿<input aria-label="连接草稿"/></label>}));
vi.mock('./LocalHistory',()=>({LocalHistory:()=> <label>历史搜索<input aria-label="历史搜索"/></label>}));
vi.mock('./LocalDeliveryPanel',()=>({LocalDeletionRecovery:()=> <p>待完成文件清理</p>}));
afterEach(()=>{cleanup();vi.mocked(localRequest).mockReset();});
it('嵌入式导航保留同一维护实例的草稿，历史首次访问才挂载，文件清理入口仍存在',async()=>{
  function Fixture(){const[tab,setTab]=useState<'connections'|'history'>('connections');return <><button onClick={()=>setTab('history')}>侧栏历史</button><button onClick={()=>setTab('connections')}>侧栏连接</button><LocalMaintenancePanel embedded activeTab={tab} onTabChange={setTab} onClose={()=>{}} revision={null}/></>;}
  const user=userEvent.setup();render(<Fixture/>);
  expect(screen.queryByRole('dialog')).toBeNull();
  expect(screen.queryByLabelText('历史搜索')).toBeNull();
  expect(screen.getByText('待完成文件清理')).toBeTruthy();
  await user.type(screen.getByRole('textbox',{name:'连接草稿'}),'未保存连接');
  await user.click(screen.getByRole('button',{name:'侧栏历史'}));
  await user.type(await screen.findByRole('textbox',{name:'历史搜索'}),'历史第二页条件');
  await user.click(screen.getByRole('button',{name:'侧栏连接'}));
  expect((screen.getByRole('textbox',{name:'连接草稿'}) as HTMLInputElement).value).toBe('未保存连接');
  expect(screen.getByLabelText('历史搜索').closest('[data-inert]')?.getAttribute('data-inert')).toBe('true');
  await user.click(screen.getByRole('button',{name:'侧栏历史'}));
  expect((screen.getByRole('textbox',{name:'历史搜索'}) as HTMLInputElement).value).toBe('历史第二页条件');
});
it('系统整页直接展示同源实际证据，保留已关闭/未启用语义及刷新恢复',async()=>{
  const at='2026-10-28T02:00:00Z';
  const report={observedAt:at,automation:{stopped:false,lastError:null,lastScanAt:at,backupsEnabled:false},plans:[],jobs:[],operations:{notification:{latest:{at,passed:false,detail:'事件投递失败'}}}};
  vi.mocked(localRequest).mockResolvedValue(report);
  const user=userEvent.setup();render(<LocalSystemStatus embedded/>);
  const table=screen.getByRole('table',{name:'运行状态'});
  await within(table).findByText('事件投递失败');
  expect(localRequest).toHaveBeenCalledTimes(1);
  expect(within(table).getByRole('cell',{name:'已关闭'})).toBeTruthy();
  expect(within(table).getByRole('cell',{name:'未启用'})).toBeTruthy();
  expect(screen.queryByRole('button',{name:/系统状态：/})).toBeNull();
  vi.mocked(localRequest).mockRejectedValueOnce(new Error('状态读取失败。'));
  await user.click(screen.getByRole('button',{name:'刷新系统状态'}));
  expect((await screen.findByRole('alert')).textContent).toBe('状态读取失败。');
  expect(within(table).queryByText('事件投递失败')).toBeNull();
  await user.click(screen.getByRole('button',{name:'刷新系统状态'}));
  await waitFor(()=>expect(screen.queryByRole('alert')).toBeNull());
  expect(await within(table).findByText('事件投递失败')).toBeTruthy();
});
